/*
 * msm_vidc additions to the V4L2 UAPI of the 4.14 sm6150 kernel.
 *
 * The 4.14 kernel carried these in include/uapi/linux/videodev2.h and
 * v4l2-controls.h. The vendor codec components were built against those
 * values, so they are kept here unchanged, private to techpack/video, rather
 * than added to the 6.1 core UAPI headers.
 *
 * Values that 6.1 has since given to something else:
 *  - enum v4l2_mpeg_video_bitrate_mode: 6.1 has CQ = 2; the vendor ABI has
 *    MBR = 2, RC_OFF = 3, CBR_VFR = 4, MBR_VFR = 5, CQ = 6 (_MSM_CQ here).
 *  - enum v4l2_mpeg_video_h264_level: 6.1 has 6_1 = 18, 6_2 = 19; the vendor
 *    ABI has UNKNOWN = 18, 6_1 = 19, 6_2 = 20 (_MSM_6_1, _MSM_6_2 here).
 *  - buffer flags 0x80, 0x200, 0x800000 and the 0x70000 timestamp-source
 *    bits have V4L2 core meanings in 6.1; see the vb2 handling in the driver.
 */
